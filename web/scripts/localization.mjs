import { correctionTargets } from "./localization-metadata.mjs";
import { renderedTokens, validateTokens } from "./localization-tokens.mjs";
import { format, resolveConfig } from "prettier";
import { readFile, writeFile, mkdir, readdir } from "node:fs/promises";
import { resolve } from "node:path";
import {
  addDomain,
  diagnosticRequirements,
  messageShape,
  readCatalog,
  validateCatalog,
  validateCoverage,
} from "./localization-policy.mjs";

const root = resolve(import.meta.dirname, "..");
const input = resolve(root, "../src/ClaimCore.Contract/Localization");
const output = resolve(root, "src/presentation/generated");
const generate = process.argv.slice(2).includes("--write");
/** @type {{languages: string[]}} */
const { languages } = JSON.parse(
  await readFile(resolve(root, "../contracts/localization-policy.json"), "utf8"),
);
/** @type {Record<string, Record<string, import("./localization-policy.mjs").Message>>} */
const catalogs = {};
const domains = [
  "ui",
  "notice",
  "token",
  "field",
  "command",
  "group",
  "authority",
  "diagnostic",
  "fault",
  "host",
  "cli",
];
const expectedInputs = languages
  .flatMap((language) => domains.map((domain) => `${language}.${domain}.json`))
  .sort();
if (
  JSON.stringify((await readdir(input)).filter((f) => f.endsWith(".json")).sort()) !==
  JSON.stringify(expectedInputs)
) {
  throw new Error("Unexpected or missing localization catalog domain.");
}
for (const lang of languages) {
  const catalog = {};
  const files = (await readdir(input))
    .filter((f) => f.startsWith(`${lang}.`) && f.endsWith(".json"))
    .sort();
  for (const file of files) {
    const entries = readCatalog(await readFile(resolve(input, file), "utf8"));
    addDomain(catalog, entries, file.slice(lang.length + 1, -5));
  }
  catalogs[lang] = catalog;
}
const generated = resolve(root, "../contracts");
const descriptors = JSON.parse(await readFile(resolve(generated, "descriptors.json"), "utf8"));
const host = JSON.parse(await readFile(resolve(generated, "openapi.json"), "utf8"));
Object.assign(catalogs["en"] ?? {}, descriptors.messages);
for (const lang of languages) {
  validateCatalog(catalogs["en"] ?? {}, catalogs[lang] ?? {}, lang);
}
const requirements = diagnosticRequirements(descriptors, host);
validateCoverage(catalogs["en"] ?? {}, descriptors, requirements);
const types = await readFile(resolve(generated, "client.ts"), "utf8");
validateTokens(catalogs["en"] ?? {}, renderedTokens(descriptors, types));
await mkdir(output, { recursive: true });
/** @type {Record<string, string>} */
const expected = {};
/** @type {Record<string, Record<string, string>>} */
const args = {};
for (const [lang, catalog] of Object.entries(catalogs)) {
  /** @type {Record<string, import("@formatjs/icu-messageformat-parser").MessageFormatElement[]>} */
  const compiled = {};
  for (const [key, message] of Object.entries(catalog)) {
    const shape = messageShape(message, lang);
    compiled[key] = shape.ast;
    if (lang === "en") {
      args[key] = shape.args;
    }
  }
  expected[`${lang}.json`] = `${JSON.stringify(compiled)}\n`;
}
expected["catalogs.ts"] =
  `${languages.map((language) => `import ${language} from "./${language}.json";`).join("\n")}\nexport const catalogs = { ${languages.join(", ")} };\n`;
expected["diagnostic-parameters.json"] = `${JSON.stringify(requirements, null, 2)}\n`;
for (const domain of domains) {
  const entries = Object.entries(args).filter(([k]) => k.startsWith(`${domain}.`));
  expected[`args.${domain}.ts`] =
    `/* Generated by localization.mjs; do not edit. */\n` +
    `export type ${(domain[0] ?? "").toUpperCase() + domain.slice(1)}Args = {\n${entries
      .map(
        ([k, shape]) =>
          `  ${JSON.stringify(k)}: ${
            Object.keys(shape).length === 0
              ? "Readonly<Record<string, never>>"
              : `{${Object.entries(shape)
                  .map(([name, role]) => ` readonly ${JSON.stringify(name)}: ${role}`)
                  .join(";")}}`
          };`,
      )
      .join("\n")}\n};\n`;
}
expected["correction-targets.json"] = `${JSON.stringify(correctionTargets(descriptors))}\n`;
expected["arguments.json"] = `${JSON.stringify(args)}\n`;
const prettierOptions = await resolveConfig(resolve(root, "package.json"));
for (const [file, raw] of Object.entries(expected)) {
  const text = await format(raw, { ...prettierOptions, filepath: file });
  const path = resolve(output, file);
  const existing = await readFile(path, "utf8").catch(() => null);
  if (generate) {
    if (existing !== text) {
      await writeFile(path, text);
    }
  } else if (existing !== text) {
    throw new Error(`Localization generated file drift: ${file}`);
  }
}
const extras = (await readdir(output)).filter((f) => !Object.hasOwn(expected, f));
if (extras.length) {
  throw new Error("Unexpected generated localization file.");
}
process.stdout.write(
  `Localization validated: ${Object.keys(args).length} keys, ${Object.keys(requirements).length} diagnostic identities, three real languages and runtime pseudolocalization.\n`,
);
