import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const webDirectory = resolve(scriptDirectory, "..");
const checker = resolve(
  webDirectory,
  "node_modules/license-checker-rseidelsohn/bin/license-checker-rseidelsohn.js",
);
const inventory = JSON.parse(
  execFileSync(process.execPath, [checker, "--production", "--json"], {
    cwd: webDirectory,
    encoding: "utf8",
    maxBuffer: 16 * 1024 * 1024,
  }),
);
const fallbacks = new Map([
  ["client-only@0.0.1", resolve(webDirectory, "node_modules/react/LICENSE")],
]);
const validatorNotice = readFileSync(
  resolve(webDirectory, "src/generated/convergence/web-v2.validators.NOTICE.txt"),
  "utf8",
).trim();
const embeddedPackages = new Set(
  Array.from(validatorNotice.matchAll(/^Package: (.+)@[^@\n]+$/gmu), (match) => match[1]),
);
if (embeddedPackages.size === 0) {
  throw new Error("The generated standalone-validator package inventory is missing.");
}

const packageName = (identity) => identity.slice(0, identity.lastIndexOf("@"));

const dependencies = Object.entries(inventory)
  .filter(([name]) => !embeddedPackages.has(packageName(name)))
  .sort(([left], [right]) => left.localeCompare(right))
  .map(([name, metadata]) => {
    const licenseFile = metadata.licenseFile ?? fallbacks.get(name);
    if (licenseFile === undefined) {
      throw new Error(`${name} does not provide reviewed redistribution license text.`);
    }
    const licenseText = readFileSync(licenseFile, "utf8").trim();
    if (licenseText.length === 0) throw new Error(`${name} has empty redistribution license text.`);
    const repository = metadata.repository === undefined ? "Not supplied" : metadata.repository;
    return { name, licenses: metadata.licenses, repository, licenseText };
  });

const grouped = Map.groupBy(dependencies, (dependency) => dependency.licenseText);
const notice = Array.from(grouped, ([licenseText, packages]) =>
  [
    ...packages.flatMap(({ name, licenses, repository }) => [
      `Package: ${name}`,
      `Declared license: ${licenses}`,
      `Upstream: ${repository}`,
      "",
    ]),
    licenseText,
  ].join("\n"),
).join("\n\n--------------------------------------------------------------------------------\n\n");

const header = [
  "ClaimCore Web — third-party notices",
  "",
  "Generated from the locked production dependency graph. Do not edit this file manually.",
  "ClaimCore itself is licensed separately under Apache-2.0 in LICENSE.",
  "",
].join("\n");
writeFileSync(
  resolve(webDirectory, "dist/THIRD-PARTY-NOTICES.txt"),
  `${header}\n${notice}\n\n${"-".repeat(80)}\n\n${validatorNotice}\n`,
);
