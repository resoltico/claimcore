// The DTCG source owns tokens; the generator checks its OKLCH ramps and emits deterministic CSS.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { format } from "prettier";
import prettierOptions from "../prettier.config.mjs";

const sourcePath = new URL("../src/theme/tokens.json", import.meta.url);
const outputPath = new URL("../src/theme/tokens.css", import.meta.url);
const tokens = JSON.parse(readFileSync(sourcePath, "utf8"));
const configuration = tokens.$extensions.claimcore;
const steps = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
const lightness = [0.975, 0.945, 0.89, 0.82, 0.72, 0.62, 0.53, 0.455, 0.385, 0.31, 0.235];
const chromaShape = [0.18, 0.3, 0.5, 0.75, 0.95, 1, 1, 0.92, 0.8, 0.65, 0.5];
/** @param {number} light @param {number} chroma @param {number} hue */
const srgb = (light, chroma, hue) => {
  const angle = (hue * Math.PI) / 180;
  const a = chroma * Math.cos(angle);
  const b = chroma * Math.sin(angle);
  const l = (light + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m = (light - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (light - 0.0894841775 * a - 1.291485548 * b) ** 3;
  return [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ].map((channel) =>
    channel <= 0.0031308 ? 12.92 * channel : 1.055 * channel ** (1 / 2.4) - 0.055,
  );
};
/** @param {number} light @param {number} chroma @param {number} hue */
const hex = (light, chroma, hue) => {
  let reduced = chroma;
  let rgb = srgb(light, reduced, hue);
  while (rgb.some((channel) => channel < -0.000001 || channel > 1.000001) && reduced > 0) {
    reduced -= 0.002;
    rgb = srgb(light, reduced, hue);
  }
  return `#${rgb
    .map((channel) =>
      Math.round(Math.min(1, Math.max(0, channel)) * 255)
        .toString(16)
        .padStart(2, "0"),
    )
    .join("")}`;
};
for (const [ramp, [hue, chroma]] of Object.entries(configuration.ramps)) {
  for (const [index, step] of steps.entries()) {
    const light = lightness[index];
    const shape = chromaShape[index];
    if (light === undefined || shape === undefined) {
      throw new Error("Incomplete ramp.");
    }
    if (tokens.color[ramp][step].$value !== hex(light, chroma * shape, hue)) {
      throw new Error(`The ${ramp}.${step} primitive differs from its OKLCH ramp.`);
    }
  }
}
const primitives = Object.entries(tokens.color).flatMap(([ramp, values]) =>
  values.$value === undefined
    ? Object.entries(values).map(([step, item]) => [`${ramp}-${step}`, item.$value])
    : [[ramp, values.$value]],
);
/** @param {string} value */
const reference = (value) => {
  const match = /^\{(color|accent)\.([\w.]+)\}$/u.exec(value);
  if (match === null || match[2] === undefined) {
    throw new Error(`A semantic colour must reference a primitive: ${value}`);
  }
  const name = (match[1] === "accent" ? "accent-" : "") + match[2].replaceAll(".", "-");
  if (match[1] === "color" && !primitives.some(([primitive]) => primitive === name)) {
    throw new Error(`Unknown colour ${value}`);
  }
  return `var(--${name})`;
};
/** @param {string} name */
const forcedColor = (name) => {
  if (name.endsWith("-bg")) {
    return "Canvas";
  }
  if (name.endsWith("-border")) {
    return "ButtonText";
  }
  return "CanvasText";
};
const lines = [
  "/* Generated by scripts/generate-theme.mjs. Edit theme/tokens.json. */",
  ":root {",
  "  color-scheme: light dark;",
];
for (const [name, value] of primitives) {
  lines.push(`  --${name}: ${value};`);
}
for (const [name, item] of Object.entries(tokens.foundation)) {
  lines.push(`  --${name}: ${item.$value};`);
}
for (const [name, item] of Object.entries(tokens.semantic)) {
  lines.push(
    `  --${name}: light-dark(${reference(item.$value.light)}, ${reference(item.$value.dark)});`,
  );
}
lines.push("  --gutter: var(--space-4);", "}");
for (const [index, accent] of configuration.accents.entries()) {
  lines.push(`${index === 0 ? ":root, " : ""}:root[data-accent="${accent}"] {`);
  for (const step of steps) {
    lines.push(`  --accent-${step}: var(--${accent}-${step});`);
  }
  lines.push("}");
}
lines.push(`:root[data-mode="light"] { color-scheme: light; }
:root[data-mode="dark"] { color-scheme: dark; }
@media (prefers-contrast: more) {
  :root {
    --text-secondary: var(--text-primary);
    --border-subtle: var(--border-control);
    --border-control: light-dark(var(--neutral-700), var(--neutral-300));
    --accent-text: light-dark(var(--accent-800), var(--accent-200));
  }
}
@media (forced-colors: active) {
  :root {
    --bg-canvas: Canvas; --bg-surface: Canvas; --bg-sunken: Canvas; --bg-raised: Canvas;
    --text-primary: CanvasText; --text-secondary: CanvasText; --text-disabled: GrayText;
    --border-subtle: CanvasText; --border-control: ButtonText; --border-strong: CanvasText;
    --accent-text: LinkText; --accent-solid: ButtonFace; --on-accent-solid: ButtonText;
    --accent-soft-bg: Canvas; --accent-soft-text: LinkText; --accent-soft-border: Highlight;
    --focus-ring: Highlight; --shadow-1: none; --shadow-2: none;
    ${Object.keys(tokens.semantic)
      .filter((name) => /^(?:state-|avatar-|danger-|warning-|success-)/u.test(name))
      .map((name) => `--${name}: ${forcedColor(name)};`)
      .join("\n    ")}
  }
  button, input, select, textarea, [role="button"], [role="tab"] { border-color: ButtonText; }
  [aria-current], [aria-selected="true"] { outline: 2px solid Highlight; }
  :root .badge, :root .pill, :root .due-chip, :root .settings-option { border: 1px solid ButtonText; }
  :root .settings-option:has(input:checked) { border-color: Highlight; }
}
@media (prefers-reduced-motion: reduce) { :root { --motion: none; } }`);
const output = await format(`${lines.join("\n")}\n`, { ...prettierOptions, parser: "css" });
if (process.argv.includes("--check")) {
  if (readFileSync(outputPath, "utf8") !== output) {
    process.stderr.write(`Stale theme: run npm run theme (${fileURLToPath(outputPath)}).\n`);
    process.exitCode = 1;
  }
} else {
  writeFileSync(outputPath, output);
}
