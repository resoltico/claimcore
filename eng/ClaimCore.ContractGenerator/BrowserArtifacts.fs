namespace ClaimCore.ContractGeneration

open ClaimCore.ClientProtocol

open System.Text
open ClaimCore.Contracts

module BrowserArtifacts =
    let private contents (endpoints: Endpoint list) typeSource endpointSource =
        endpoints
        |> List.iter (fun (endpoint: Endpoint) ->
            SchemaSupport.document endpoint.Request
            SchemaSupport.document endpoint.Response)

        let entries =
            endpoints
            |> List.map (fun endpoint ->
                let schema document =
                    EndpointCatalog.schema document |> CanonicalContract.text

                "  "
                + System.Text.Json.JsonSerializer.Serialize(endpoint.Identifier)
                + ": { request: "
                + schema endpoint.Request
                + ", response: "
                + schema endpoint.Response
                + " }")
            |> String.concat ",\n"

        "// Generated by ClaimCore.ContractGenerator. Do not edit.\n"
        + "import { admitBytes, validateSchema, validateStructure, schemaIssue, type SchemaDocument } from '../web/src/protocol/schema';\n"
        + endpointSource
        + typeSource
        + "export const wireSchemas: Readonly<Record<keyof RequestByEndpoint, {request: SchemaDocument; response: SchemaDocument}>> = {\n"
        + entries
        + "\n};\n"
        + "export const hostFailureSchema: SchemaDocument = "
        + (EndpointCatalog.schema HostFailures.schema |> CanonicalContract.text)
        + ";\n"
        + "export const isObject = (value: unknown): value is Record<string, unknown> => typeof value === 'object' && value !== null && !Array.isArray(value);\n"
        + "export function isResponse<K extends keyof ResponseByEndpoint>(endpoint: K, value: unknown): value is ResponseByEndpoint[K] { return validateSchema(wireSchemas[endpoint].response, value); }\n"
        + "export function decodeResponse<K extends keyof ResponseByEndpoint>(endpoint: K, bytes: Uint8Array): ResponseByEndpoint[K] { const value = admitBytes(bytes); if (!isResponse(endpoint, value)) throw new Error('Invalid endpoint response.'); return value; }\n"
        + "export function isHostFailure(value: unknown, status: number): value is HostFailure { return validateSchema(hostFailureSchema, value) && typeof value === 'object' && value !== null && 'status' in value && value.status === status; }\n"
        + "export function buildRequest<K extends keyof RequestByEndpoint>(endpoint: K, value: unknown): RequestByEndpoint[K] { if (!hasRequestStructure(endpoint, value)) throw new Error('Invalid endpoint request structure.'); return value; }\n"
        + "function hasRequestStructure<K extends keyof RequestByEndpoint>(endpoint: K, value: unknown): value is RequestByEndpoint[K] { return validateStructure(wireSchemas[endpoint].request, value); }\n"
        + "export function requestIssue<K extends keyof RequestByEndpoint>(endpoint:K,value:unknown):ReadonlyArray<string>|null { return schemaIssue(wireSchemas[endpoint].request,value); }\n"
        + "export function isRequest<K extends keyof RequestByEndpoint>(endpoint: K, value: unknown): value is RequestByEndpoint[K] { return validateSchema(wireSchemas[endpoint].request, value); }\n"
        + BrowserCorrelation.source
        |> Encoding.UTF8.GetBytes

    let source () =
        contents
            EndpointCatalog.all
            "import type { RequestByEndpoint, ResponseByEndpoint, HostFailure } from './types';\n"
            "import { endpoints } from './endpoint-catalog';\n"

    let sourceFor (endpoints: Endpoint list) =
        let types name select =
            "type "
            + name
            + " = { "
            + (endpoints
               |> List.map (fun (endpoint: Endpoint) ->
                   System.Text.Json.JsonSerializer.Serialize(endpoint.Identifier)
                   + ": "
                   + Schema.typeScript (select endpoint)
                   + ";")
               |> String.concat " ")
            + " };\n"

        let definitions =
            endpoints
            |> List.collect (fun endpoint -> endpoint.Response.Definitions)
            |> List.distinct

        let declarations =
            definitions
            |> List.map (fun (name, schema) ->
                "type " + name + " = " + Schema.typeScript schema + ";\n")
            |> String.concat ""

        let typeSource =
            declarations
            + types "RequestByEndpoint" (fun endpoint -> endpoint.Request.Root)
            + types "ResponseByEndpoint" (fun endpoint -> endpoint.Response.Root)
            + "type HostFailure = unknown;\n"

        let endpointSource =
            "const endpoints = "
            + (EndpointCatalog.metadataFor endpoints |> CanonicalContract.text |> _.TrimEnd())
            + " as const;\n"

        contents endpoints typeSource endpointSource
