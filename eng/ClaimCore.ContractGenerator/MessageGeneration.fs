namespace ClaimCore.ContractGeneration

open System.Text
open System.Text.Json
open ClaimCore.Contract
open ClaimCore.Contract.Protocol

/// Types and runtime argument metadata are projections of admitted templates.
module MessageGeneration =
    let private quote (value: string) = JsonSerializer.Serialize value

    let private json value =
        WireWriter.bytes value |> Encoding.UTF8.GetString

    let private requirements =
        [
            for definition in Refusals.definitions do
                let parameters =
                    definition.Parameters
                    |> List.map (fun parameter ->
                        parameter.Name,
                        JsonValue.Object
                            [
                                "minimum", JsonValue.Integer(int64 parameter.Minimum)
                                "maximum", JsonValue.Integer(int64 parameter.Maximum)
                            ])

                yield "diagnostic." + definition.Id, JsonValue.Object parameters
            for _, code in CoreFaults.all do
                yield "fault." + code, JsonValue.Object []
            for failure in HostFailures.all do
                yield "host." + HostFailures.code failure, JsonValue.Object []
        ]
        |> Map.ofList
        |> Map.toList
        |> JsonValue.Object

    let source (catalogs: Map<string, Map<string, Template>>) =
        let english = catalogs["en"]

        let shapes =
            english
            |> Map.toList
            |> List.map (fun (key, template) ->
                key,
                Template.arguments template
                |> Set.toList
                |> List.map (fun name -> name, JsonValue.String "string")
                |> JsonValue.Object)
            |> JsonValue.Object

        let declarations =
            english
            |> Map.toList
            |> List.map (fun (key, template) ->
                let arguments = Template.arguments template |> Set.toList

                let value =
                    if arguments.IsEmpty then
                        "Readonly<Record<string, never>>"
                    else
                        arguments
                        |> List.map (fun name -> "readonly " + quote name + ": string")
                        |> String.concat "; "
                        |> fun value -> "{ " + value + " }"

                "  " + quote key + ": " + value + ";")
            |> String.concat "\n"

        let corrections =
            OperationCatalog.caseDefinitions
            |> List.collect (fun act ->
                match act.Inputs with
                | ActInputShape.CorrectionGroups groups ->
                    groups |> List.map (fun group -> CorrectionGroup.token group.Name)
                | _ -> [])
            |> List.distinct
            |> List.map (fun name -> name + ".action", JsonValue.String name)
            |> JsonValue.Object

        [
            "// Generated by ClaimCore.ContractGenerator. Do not edit."
            yield!
                LocalizationPolicy.languages
                |> List.map (fun language ->
                    "import "
                    + language
                    + " from \"../src/ClaimCore.Contract/Localization/"
                    + language
                    + ".json\";")
            "export const catalogs = { "
            + String.concat ", " LocalizationPolicy.languages
            + " } as const;"
            "export type MessageArgs = {\n" + declarations + "\n};"
            "export type MessageKey = keyof MessageArgs;"
            "export const messageShapes = " + json shapes + " as const;"
            "export const diagnosticParameters = " + json requirements + " as const;"
            "export const correctionTargets = " + json corrections + " as const;"
        ]
        |> String.concat "\n"
        |> fun text -> Encoding.UTF8.GetBytes(text + "\n")
